#!/usr/bin/env python3
"""Compacts the haptic score masters in scores/*.json and writes them into index.html between the two marker comments.
Run after editing a master:  python3 tools/gen-score.py      (--check only verifies index.html is up to date)
The master format is luna-haptic v1 (see scores/README.md). The app keeps only what playback needs: no labels, notes or anchors."""
import os, re, sys, json
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
START, END = '/* ===== haptic scores: generated by tools/gen-score.py, do not edit by hand ===== */', '/* ===== end haptic scores ===== */'
def r(x): return round(x, 3)
def cue(c):
    o = {'t': r(c['t']), 'k': c['kind'], 'l': c['layer']}
    for a, b in (('i', 'i'), ('s', 's'), ('d', 'd'), ('bpm', 'b'), ('gap', 'g')):
        if a in c: o[b] = r(c[a])
    if 'env' in c: o['e'] = [[r(x), r(y)] for x, y in c['env']]
    if 'taps' in c: o['tp'] = [[r(x), r(y)] for x, y in c['taps']]
    if 'tail' in c: o['tl'] = [r(c['tail'][0]), r(c['tail'][1])]
    if c.get('skip'): o['sk'] = [[r(x), r(y)] for x, y in c['skip']]
    if c.get('optional'): o['o'] = 1
    return o
def build():
    out = []
    d = os.path.join(root, 'scores')
    for f in sorted(os.listdir(d)):
        if not f.endswith('.json'): continue
        m = json.load(open(os.path.join(d, f)))
        pb = m.get('playback', {})
        s = {'v': 1, 'len': m['track']['scoreLength'], 'gain': pb.get('masterGain', 1), 'bed': pb.get('bedCeiling', .66), 'cues': [cue(c) for c in sorted(m['cues'], key=lambda c: c['t'])]}
        out.append('SCORES[%s]=%s;' % (json.dumps(m['track']['title'].upper()), json.dumps(s, separators=(',', ':'))))
    return START + '\n' + '\n'.join(out) + '\n' + END
p = os.path.join(root, 'index.html'); h = open(p, encoding='utf8').read()
i, j = h.index(START), h.index(END) + len(END)
new = h[:i] + build() + h[j:]
if '--check' in sys.argv:
    if new != h: print('index.html is out of date: run tools/gen-score.py'); sys.exit(1)
    print('score data up to date'); sys.exit(0)
open(p, 'w', encoding='utf8').write(new); print('wrote', len(build()), 'bytes of score data')
